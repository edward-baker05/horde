namespace polish {

bool enabled() {
    return g_polish;
}

void setEnabled(bool on) {
    g_polish = on;
}

} // namespace polish

const char* tr(const char* english) {
    if (!g_polish) {
        return english;
    }
    const auto& table = translations();
    const auto found = table.find(english);
    return found != table.end() ? found->second : english;
}

